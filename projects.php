<hr class="style-one" />
As a soloist I do work completely alone, from the creation (composition, orchestration and arrangements), even until the production (recording, performance, mixing and mastering). <br />On the performance I play Guitars and Bass, but other instruments for the orchestration are MIDI programmed.
<hr class="style-one" />
<h5>Complete productions until today:</h5>
<a href="discography">Fragments Of Future Memories (2016)</a><br />
<a href="discography">MISCHUNG (2009)</a>
</div>

