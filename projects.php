In 2014 the Bassist of my band "Kolors Of Zound" invited me to play in another group where he played the Tuba. The "Guglhupf Ensemble" is a Wienerlied group formed by two Singers, one Cello, one Tuba and one Guitar. At the beginning I was a bit skeptic, but then I started to enjoy the project very much.
