<hr class="style-one" />
The story of Kolors Of Zound started almost at the same time with my solo project. After composing its debut album "Tales From A White Land", it took me four years to find the right musicians to record and perform its music. Between 2014 and 2015 the band was active playing in Vienna, but ended up splitting in 2015.
<hr class="style-one" />
<h5>Complete productions until today:</h5>
<a href="discography">Tales From A White Land (2014)</a>
