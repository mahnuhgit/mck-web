<hr class="style-one" />
    Manuel Calvo Kamper, fue el primer maestro de guitarra que tuve.<br />
 Después de haberme ayudado a lograr mi objetivo que era tocar guitarra e interpretar las canciones que me gustaban, vi en la música el camino que quería tomar para mi vida.<br />
 En ese momento hablé con Manuel y le dije que necesitaba ayuda para superar las pruebas de admición en la Universidad, y desde ese momento se volvió el maestro que con gran entusiasmo y disposición me acompañó durante todos los años de estudio y me ayudó a superar todas las dificultades que me permitieron hacer de mi proyecto de vida una realidad.
 <br />
Las clases con Manuel son entretenidas e interesantes, siempre encontré respuestas concretas y constructivas a todas las preguntas que le hice. También hay que resaltar que los temas referentes a la carrera los tiene muy claros y en un orden tal que logra que cada tema se trate muy sencillamente pero con gran profundidad, y eso le permite a uno entender y manejar con seguridad el lenguaje de la música.
<br />
En la actualidad Manuel es parte fundamental en el desarrollo de mi trabajo ya que con los años logré convertirme en productor y Manuel es ahora compositor, arreglista y músico de sesión en mi estudio. Además he tenido el gusto de mezclar uno de los discos de su banda Kolors Of Zound.
