<hr class="style-one" />
Manuel Calvo Kamper fue mi maestro de guitarra del 2010 al 2014, y considero que este fue uno de los momentos más importantes de mi vida musical.
En ese entonces (a la edad de 16) tomé la decisión de hacer de la música mi profesión, con lo cual Manuel me ayudó seriamente.
<br />
Gracias a las clases con Manuel y su constante apoyo, pude asistir a la Universidad "Anton Bruckner" en Linz, en donde recibí mi licenciatura en artes y pedagogía instrumental enfocada a la guitarra Jazz en el 2017.
<br />
Su vasto conocimiento me permitió entrar a la Universidad con un conocimiento teórico, al igual que un entrenamiento auditivo más avanzado de lo que la Universidad me ofrecía durante los primeros semestres. Además, la gran cantidad de estilos musicales que domina y su gran talento para tocar y componer han sido una influencia tremenda en mi carrera.
<br />
No sólo me ayudó a mejorar como guitarrista, sino también a convertirme en un músico multifuncional.
<br />
Siempre ha sido una gran inspiración y sigue siendo un gran maestro y amigo. 

