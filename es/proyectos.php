En el 2008 fui contratado por "Grupo Gea - Proyecto K" en Bogotá/Colombia para componer la música del musical "Nació Un Campeón". Este fue mi primer trabajo como compositor y fue muy emocionante trabajar con estudiantes de actuación, cuyas voces hicieron parte en la grabación.
