<h6>PROYECTOS</h6>
<div class="sub-container">
    <table width="100%">
  <tr>
    <td width="150px">
      <a href="discografia"><img class="img" src="../pics/fragments.png" alt="Fragments-Of-Future-Memories" /></a>
