<hr class="style-one" />
En el 2014 el bajista de mi banda "Kolors Of Zound" me invitó a tocar en otro grupo en donde el tocaba la tuba. El "Guglhupf Ensemble" es un grupo de canción vienés formado por dos cantantes, un cello, una tuba y una guitarra. Al comienzo estaba un poco escéptico, pero después empecé a gustar mucho del proyecto.
</div>

