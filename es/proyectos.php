<hr class="style-one" />
Como solista trabajo verdaderamente solo, desde la creación (composición, orquestación y arreglos), incluso hasta la producción (grabación, interpretación, mezcla y masterización). <br />En la interpretación toco guitarra y bajo, pero otros instrumentos en la orquestación los programo en MIDI.
<hr class="style-one" />
<h5>Producciones completas hasta hoy:</h5>
<a href="discografia">Fragments Of Future Memories (2016)</a><br />
<a href="discografia">MISCHUNG (2009)</a>
</div>

<div class="sub-container">
    <table width="100%">
  <tr>
    <td width="150px">
      <a href="http://kolorsofzound.com" target="_blank"><img class="img" src="../pics/kolors.png" alt="Kolors-Of-Zound" /></a>
    </td>
    <td width="5px">
    </td>
    <td valign="top">
    <h4>KOLORS OF ZOUND <br />(2009 - 2015)</h4>
    <br />
    <a href="http://kolorsofzound.com" target="_blank"><button class="contact-button">Visit Website</button></a>
   </td>
  </tr>
</table>
<hr class="style-one" />
La historia de Kolors Of Zound comenzó casi al mismo tiempo que mi proyecto solista. Después de componer su debut álbum "Tales From A White Land", me tomó cerca de cuatro años en encontrar los músicos adecuados para poder grabar e interpretar su música. Del 2014 al 2015 la banda estuvo tocando activamente en Viena, sin embargo ésta se disolvió en el 2015.
<hr class="style-one" />
<h5>Producciones completas hasta hoy:</h5>
<a href="discografia">Tales From A White Land (2014)</a>
<hr class="style-one" />
<h5>Gente que colaboró con Kolors Of Zound:</h5>
<ul>
<li>Hannes Drobetz (Voz)</li>
<li>Christo Popov (Teclados)</li>
<li>Werner Haider (Bajo en vivo)</li>
<li>Constantin Pammer (Batería en vivo)</li>
<li>Roberto Sensi (Bajo en estudio)</li>
<li>Michal Robert Piatek (Líricas de la canción "Insane")</li>
<li>Dominik Scherr (Batería en estudio de la canción "Orange Hope")</li>
<li>Juan Carlos Andrade (Ingeniero de mezcla)</li>
<li>Daniel Celis Arias (Ingeniero de masterización)</li>
</ul>
</div>

