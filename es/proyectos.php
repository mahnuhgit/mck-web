Del 2011 al 2012 fui contratado por el letrista "Martin Missbichler" para orquestar, cantar, interpretar y producir algunas de sus ideas. Durante este tiempo logramos producir algunas canciones para un EP llamado "Rock & Roll - Sing It All".
