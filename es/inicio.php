<h6>LA HISTORIA</h6>
Mi vida musical comenzó en 1996 a la edad de 15 años.
<br />
Antes pensaba en estudiar informática, pero tan pronto como toqué la guitarra por primera vez, ésta terminó convirtiéndose en mi obsesión.
<br /><br />
Mientras estaba en el colegio, José Vicente Sáenz fue mi primer maestro. De él aprendí las bases de la técnica y la teoría, él me insistió varias veces en que yo debería estudiar música, y aunque me sentía tentado a hacerlo, todavía estaba seguro de que mi carrera estaba en la informática. 
<br /><br />
Después del colegio, de 1998 a 1999, tomé clases privadas con Germán Darío Liceaga, el cual tocó con las bandas Aterciopelados y Juanes. 
Este maestro me ayudó considerablemente a mejorar mi técnica como guitarrista y me abrió las puertas a un mundo lleno de virtuosismo y musicalidad. Durante esos dos años, él me mostró músicos magníficos, los cuales yo jamás pensé que pudiesen existir, y fue en ese momento cuando decidí convertirme en músico. 
<br /><br />
En 1999 entré a la "Universidad El Bosque" en Bogotá/Colombia, donde hice mis estudios en música. En los dos primeros semestres estudié guitarra clásica con la profesora Irene Gómez, pero mi interés por la guitarra popular era mucho más grande, así que del 2000 al 2003 estudié Jazz con los profesores Gabriel Rondón, Kike Mendoza y Ricardo Márquez Romero, tres grandes músicos a quienes debo la mayor parte de lo que sé sobre armonía e improvisación.
<br /><br />
Después de la Universidad salí de Colombia y viajé a los Estados Unidos en donde viví por cuatro años y en ese tiempo toqué con varias bandas, aunque mayormente con dos, las cuales eran muy diferentes en estilo: Robert Lee Miller (Country Music) & Shangri La (Nujazz)
<br /><br />
En el 2008 la vida me llevó de vuelta a Colombia. Allí trabajé como maestro de técnica vocal en la academia de actuación "Gea Proyecto K", y también compuse la música para dos producciones realizadas por la misma academia. Ésta fue la primera vez que trabajé como compositor y desde ese momento, ser un compositor ha sido uno de los pilares de mi vida musical.
<br /><br />
Finalmente en el 2009 vine a Viena. Aquí he trabajado mayormente como maestro de guitarra y teoría aplicada, aunque obviamente también como guitarrista y compositor. 
<br />
Antes mencionaba que quería estudiar informática. 
<br />
Bueno... de hecho no he dejado los computadores del todo. El uso de computadores para la producción de audio y programación MIDI es indispensable para mí, y además con los años he aprendido algo de diseño y codificación. Un ejemplo de ello es este sitio web, el cual no es el único que he hecho. 
<br /><br />
También desde que vine a Austria mi deseo por aprender idiomas empezó a crecer y ahora puedo ofrecer mis clases en cuatro de ellos... Español, Inglés, Alemán e Italiano. 
<br /><br />
En todos estos años he tocado en varios proyectos de diferentes estilos musicales (Pop, Jazz, Rock, Wienerlied, Metal, Funk, Latin...), y crecido como compositor y productor.
<br />
Si deseas escuchar mi trabajo como compositor, por favor ve <a href="discografia" title="Discografía">aquí</a>. 
<br /><br />
A la fecha he compuesto, orquestado y arreglado 54 piezas (de ellas 35 están ya publicadas), y actualmente me encuentro trabajando en mi quinta producción, la cual planeo terminar el próximo año.
<br /><br />
Continuará...
