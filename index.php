<h6>THE STORY</h6>

My musical life started in 1996 at the age of 15.
<br />
Back then, I thought about studying informatics but as soon as I played guitar for the first
time, it ended up becoming an obsession.
<br /><br />
While being at school, José Vicente Sáenz was my first guitar teacher. From him I learned
the basics of guitar techniques and some musical theory, he insisted several times that I
should study music, and although it was very tempting, I still was sure that my career
would be in informatics. 
<br /><br />
After school, from 1998 to 1999, I took private lessons with Germán Darío Liceaga, who
played with the bands Aterciopelados and the former band of Juanes. 
<br />
This teacher helped me improve considerably my technique as a guitarist, and showed
me a world of virtuosism and complex musicality. During those two years he showed me
astonishing musicians, that I never thought they could exist, and it was at that moment,
when I realized that I should become a musician. 
<br /><br />
In 1999 I went to the "University - El Bosque" in Bogotá/Colombia, where I made my
studies in music. During the first two semesters I studied classical guitar with Prof. Irene
Gómez, but my true interest lay in modern guitar, so from 2000 to 2003 I studied Jazz
with Prof. Gabriel Rondón, Kike Mendoza and Ricardo Márquez Romero, three fantastic
musicians to whom I owe most of what I know about harmony and improvisation.
<br /><br />
After the University I left Colombia and travelled to the USA where I lived four years, and
during that time I played with several bands, but mostly with two which styles were very
different from each other: Robert Lee Miller (Country Music) & Shangri La (Nujazz).
<br /><br />
In 2008 life brought me back to Colombia, there I worked as a vocal coach at the acting
academy "Gea Proyecto K", and also composed the music for two productions made by
the same academy.
<br />
That was the first time that I worked as a composer and since then, being a composer has
become one of the pillars of my musical life.
<br /><br />
Finally in 2009 I came to Vienna. Here I work mostly at giving guitar and applied theory
lessons, but obviously as a guitarist and composer as well.
<br /><br />
I mentioned at the beginning that I wanted to study informatics.
<br />
Well... I haven't left computers after all, the use of computers for audio production and
MIDI programming is something I rely all the time, plus with the years I've learned some
design and coding as well... An example of it is this website, which isn't the only one I've
made.
<br />
<a href="web-design" title="Web-Design">Click if you want to see my work as a web designer.</a>
<br /><br />
Also, since I came to Austria, my wish for learning languages began to grow, thus now I
offer my lessons in four languages... English, German, Spanish & Italian.
