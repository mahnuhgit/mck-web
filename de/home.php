<h6>DIE GESCHICHTE</h6>
Mein Leben als Musiker begann 1996, im Alter von 15 Jahren.
<br />
Davor dachte ich mehr daran Informatik zu studieren, doch als ich zum ersten mal Gitarre spielte, wurde dies zu meiner großen Leidenschaft. 
<br /><br />
In den folgenden zwei Jahren unterrichtete mich José Vicente Sáenz, bei dem ich die Grundlagen der Gitarre und Musiktheorie lernte, er hat mich oft auf Musik zu studieren bestanden, und obwohl die Idee mich besonders angesprochen hat, war ich noch sicher um Informatik zu studieren. 
<br /><br />
Von 1998 bis 1999 nahm ich Privatunterricht bei Germán Darío Liceaga, der mit den Bands Aterciopelados und Juanes spielte. Dieser Lehrer hat meine Technik als Gitarrenspieler sehr verbessert und zeigte mir eine musikalische Welt voller Virtuosität. Während dieser zwei Jahren hat er mir großartige Musiker gezeigt, die ich nie gedacht habe, dass sie existieren könnten. Und in diesem Moment habe ich endlich entschieden Musiker zu werden.
<br /><br />
Im Jahr 1999 begann ich mein Studium als Musiker an der "Universität El Bosque" in Bogotá/Kolumbien.
Die ersten zwei Semester lernte ich klassische Gitarre bei Prof. Irene Gómez, aber mein Interesse der modernen Gitarre war noch größer, und von 2000 bis 2003 lernte ich Jazz bei den Professoren Gabriel Rondón, Kike Mendoza und Ricardo Márquez Romero. Den Großteil meines Wissens über moderne Harmonie und Improvisation habe ich durch diese drei wunderbare Musiker erlangt.  
<br /><br />
Nach der Universität habe ich Kolumbien verlassen und lebte vier Jahren in den USA. Während dieser Zeit habe ich mit verschiedenen Bands gespielt aber meistens mit zwei, die weit von einander in der Musikrichtung waren: Robert Lee Miller (Country Music) & Shangri La (Nujazz)
<br /><br />
In 2008 habe ich zurück nach Kolumbien gereist. Dort habe ich bei der Schauspielakademie "Gea Proyecto K" als Vocal Coach gearbeitet, und bei der gleichen Akademie habe ich auch die Musik von zwei Musicals komponiert. Dies war das erste Mal, dass ich als komponist gearbeitet habe und seitdem ist die Komposition eine der Pfeiler meines musikalischen Lebens.
<br /><br />
Endlich in 2009 bin ich nach Wien gekommen. Hier arbeite ich meistens als Lehrer, obwohl auch als Gitarrist und Komponist. 
<br />
Wie bereits erwähnt, wollte ich Informatik studieren. Na gut... Ich habe Computer eigentlich nicht verlassen. Für Audio Produktion und MIDI Programmierung, bin ich natürlich sehr abhängig von Computern, und mit den Jahren habe ich auch ein bisschen Design so wie etwas Kodierung gelernt... Diese Webseite ist ein Beispiel davon, und es ist nicht die einzige Webseite, die ich gemacht habe. 
<br /><br />
Auch, seitdem ich nach Österreich gekommen bin, hat mein Wunsch für Sprachen zu lernen gewachsen und jetzt kann ich auf vier Sprachen unterrichten... Deutsch, Englisch, Spanisch & Italienisch. 
<br /><br />
Während all dieser Jahre habe ich mit verschiedenen Projekten gespielt (Pop, Jazz, Rock, Wienerlied, Metal, Funk, Latin...) und als Komponist sowie als Produzent gewachsen.
<br />
Falls Interesse an meiner Arbeit als Komponist, können Sie <a href="diskographie" title="Diskographie">hier</a> anhören.</a> 
<br /><br />
Bis heute habe ich 54 Stücke komponiert, orchestriert und arrangiert (35 von denen sind schon veröffentlicht), und derzeit arbeite ich an meiner 5te Produktion, die ich für nächstes Jahr fertigzumachen plane.
<br /><br />
Fortsetzung folgt...
