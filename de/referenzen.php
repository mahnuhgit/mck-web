<hr class="style-one" />
    Manuel Calvo Kamper ist seit 2012 mein Gitarrenlehrer. Nach langer Suche und unzähligen Inseraten die ich durchstöbert hatte bin ich dann auf Manuel gestoßen.
    <br />
 Bereits in der ersten Stunde habe ich mich sehr wohl gefählt und war überzeugt von seinem musikalischen Wissen und Fähigkeiten am Instrument. Dank Manuel konnte ich große Fortschritte auf der Gitarre machen, mein musiktheoretisches Wissen umfangreich erweitern und habe viele neue Musikgenres entdeckt und spielen gelernt.
 <br />
 Aufgrund seiner geduldigen und freundlichen Art sind die Stunden mit ihm äußerst angenehm.
 <br />
 Während dieser Jahren bin ich zu der Überzeugung gekommen, dass Manuel der mit Abstand einer der besten Gitarrenlehrer Wiens ist und er ist in dieser Zeit zu einem guten Freund geworden.
