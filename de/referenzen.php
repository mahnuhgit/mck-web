<hr class="style-one" />
    Manuel Calvo Kamper war mein erster Gitarrenlehrer.<br />
 Nach dem er mir um meine Lieblingslieder zu lernen geholfen hat, habe ich wahrgenommen, dass mein beruflicher Werdegang die Musik sein sollte.<br />
 Er hat mir auch mit der Aufnahmeprüfung der Universität geholfen, sogar durch mein ganzes Studium um Hindernisse zu überwinden, damit ich mein Lebensprojekt verwirklichen könnte.
 <br />
 Die Stunde mit Manuel sind unterhaltsam und interessant, ich habe immer konkrete und konstruktive Antworten für alle meine Fragen gefunden. Noch dazu möchte ich zur Geltung bringen, dass er alle Fächer vertieft ohne sie zu erschweren.
<br />
Manuel ist derzeit ein wesentlicher Bestandteil meiner Arbeit, weil mit den Jahren bin ich Produzent geworden und Manuel hilft mir als Komponist, Arrangeur und Session-Musiker.
