<hr class="style-one" />
Manuel Calvo Kamper war mein Gitarrenlehrer von 2010 bis 2014, einer der wichtigsten Zeiträume meines musikalischen Lebens.
Damals, im Alter von 16 Jahren, habe ich die Entscheidung um Musik als mein Beruf zu studieren getroffen und Manuel hat mir damit wirklich sehr geholfen.
<br />
Wegen Manuels Stunden und ständige Unterstützung, konnte ich an der Anton Bruckner Privatuniversität in Linz teilnehmen, wo ich meinen Kunst Bachelor "Instrumental (Gesangs) Pädagogik - Jazz Gitarre" (2017) bekommen habe.
<br />
Seine weite Kenntnis von Theorie hat mich an der Universität mit einer sehr fortgeschrittenen Kenntnis und Gehörbildung teilnehmen zugelassen.
Noch dazu, seine vielfältige Musikrichtungen (besonders Progressive Rock / Metal), Songwriting so wie seine Kenntnis auf der akustischen und elektrischen Gitarre haben eine sehr große Auswirkung auf meiner Karriere gehabt.
<br />
Er hat mir nicht nur als Gitarrist zu verbessern geholfen, aber auch um einen vielseitigen Musiker zu werden.
<br />
Er bleibt noch für mich als eine große Inspiration, Lehrer und Freund.

    </div>
