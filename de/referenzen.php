    Manuel ist ein hochqualifizierter Gitarrist und Lehrer. 
Er hat unsere Tochter von 2014 bis 2017 unterrichtet und hat ihr seine Kenntnis so wie seine Hochstimmung weitergeleitet.<br />
Sie hat sehr schnell komplizierte Lieder auf der Gitarre gelernt und es war eine Entzückung ihre musikalische Entwicklung zu sehen.
Durch alle dieser Jahren, war Manuel immer freundlich und flexibel.
<br />
Concrete Garden by Marilies Jagsch war das erste Lied, dass er zu unsere Tochter beigebracht hat und Manuel hat ihr dieses Lied in wenigen Stunden unterrichtet.
<br />
Ich kann Manuel als Gitarrenlehrer zweifellos empfehlen.
