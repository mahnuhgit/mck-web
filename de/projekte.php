In 2014 der Bassist meiner Band "Kolors Of Zound" hat mich eingeladen, um in einem anderen Projekt zu spielen, wo er die Tuba spielte. Die Besetzung der Wienerliedsgruppe "Guglhupf Ensemble" ist zwei Sänger, ein Cello, eine Tuba und eine Gitarre. Am Anfang war ich ziemlich skeptisch aber danach habe ich diese Musik sehr gerne gespielt.
