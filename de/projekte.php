<hr class="style-one" />
Als Solist arbeite ich wirklich alleine, aus der Erstellung (Komposition, Orchestrierung und Arrangements), bis zur Produktion (Aufnahme, Interpretation, Mixing und Master). <br />Als Interpret spiele ich Gitarre und Bass aber andere Instrumentente der Orchestrierung sind MIDI programmiert.
<hr class="style-one" />
<h5>Fertige Produktionen bis heute:</h5>
<a href="diskographie">Fragments Of Future Memories (2016)</a><br />
<a href="diskographie">MISCHUNG (2009)</a>
</div>

<div class="sub-container">
    <table width="100%">
  <tr>
    <td width="150px">
      <a href="http://kolorsofzound.com" target="_blank"><img class="img" src="../pics/kolors.png" alt="Kolors-Of-Zound" /></a>
    </td>
    <td width="5px">
    </td>
    <td valign="top">
    <h4>KOLORS OF ZOUND <br />(2009 - 2015)</h4>
    <br />
    <a href="http://kolorsofzound.com" target="_blank"><button class="contact-button">Visit Website</button></a>
   </td>
  </tr>
</table>
<hr class="style-one" />
Die Geschichte Kolors Of Zounds hat fast gleichzeitig mit meinem solo project angefangen. Nachdem ich sein Debutalbum "Tales From A White Land" komponiert habe, musste ich vier Jahre lang suchen, bis ich die richtige Musiker für die Produktion finden konnte. Zwischen 2014 und 2015 die Band hat aktiv in Wien gespielt aber in 2015  haben wir entschieden nicht weiter zu gehen.
<hr class="style-one" />
<h5>Fertige Produktionen bis heute:</h5>
<a href="diskographie">Tales From A White Land (2014)</a>
<hr class="style-one" />
<h5>Leute die mit Kolors Of Zound gearbeitet haben:</h5>
<ul>
<li>Hannes Drobetz (Stimme)</li>
<li>Christo Popov (Keyboards)</li>
<li>Werner Haider (Bass Live)</li>
<li>Constantin Pammer (Schlagzeug Live)</li>
<li>Roberto Sensi (Bass im Studio)</li>
<li>Michal Robert Piatek (Text des Liedes "Insane")</li>
<li>Dominik Scherr (Schlagzeug im Studio für das Lied "Orange Hope")</li>
<li>Juan Carlos Andrade (Mixing Tontechniker)</li>
<li>Daniel Celis Arias (Master Tontechniker)</li>
</ul>
</div>

