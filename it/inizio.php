<h6>LA STORIA</h6>
La mia vita musicale è iniziata nel 1996 all'età di 15 anni.
<br />
Prima pensavo di studiare informatica, ma appena ho suonato la chitarra per la prima volta, questa è diventata una ossessione.
<br /><br />
Mentre ero a scuola, José Vicente Sáenz è stato il mio primo insegnante. Da lui ho imparato le fondamente della tecnica e la teoria, lui ha insistito molte volte che io studiassi musica, ma pur mi sentivo tentato di farlo, ero certo che la mia carriera sarebbe l'informatica. 
<br /><br />
Dopo la scuola dal 1998 al 1999 ho preso lezioni con Germán Darío Liceaga, il quale aveva suonato coi gruppi Aterciopelados e Juanes.
Questo insegnante mi ha aiutato notevolmente a migliorare la mia tecnica come chitarrista e mi ha aperto le porte a un mondo pieno di virtuosismo e musicalità.
Durante questi due anni, lui mi ha mostrato magnifici musicisti, i quali non pensavo che potessero esistere, e fu allora quando ho pensato che il mio desiderio di essere musicista non dovrebbe vivere solo all'interno di me ma doveva esternarsi e avverarsi. 
<br /><br />
Nel 1999 sono andato all'Università - El Bosque a Bogotá/Colombia, dove ho fatto i miei studi di musica. Durante i due primi semestri ho studiato chitarra classica con la professoressa Irene Gómez, ma il mio interesse per la chitarra populare era tanto più grande, perciò dal 2000 al 2003 ho studiato Jazz coi professori Gabriel Rondón, Kike Mendoza e Ricardo Márquez Romero, tre grandi musicisti ai quali devo la maggiore parte della mia conoscenza su armonia e improvvisazione.
<br /><br />
Dopo l'Università sono uscito da Colombia e ho viaggiato negli Stati Uniti dove ho vissuto per quattro anni e durante quel tempo ho suonato con diversi gruppi, anche se soprattutto con due, i quali erano molto diversi nel loro stile: Robert Lee Miller (Country Music) & Shangri La (Nujazz)
<br /><br />
Nel 2008 la vita mi ha portato di nuovo in Colombia. Lì ho lavorato come insegnante di tecnica vocale nella scuola di recitazione "Gea Proyecto K", e ho composto la musica per due produzioni fatte dalla stessa scuola. Quella è stata la prima volta che ho lavorato come compositore e da quel momento essere un compositore è diventato uno dei  pilastri della mia vita musicale.
<br /><br />
Finalmente nel 2009 sono arrivato a Vienna. Qui lavoro maggiormente come insegnante di chitarra e teoria applicata, ma ovviamente anche come chitarrista e compositore. Prima parlavo su studiare informatica. Bene... in realtà non ho lasciato i computer del tutto. L'uso di computer per la produzione di audio e la programmazione di MIDI è indispensabile per me, e anche nel corso degli anni ho imparato un po' di disegno e codificazione. Un essempio di quello è questo sito web, il quale non è l'unico che ho fatto. Anche dal momento in cui sono arrivato in Austria, il mio desiderio di imparare altre lingue ha cominciato a crescere e adesso posso offrire lezioni di chitarra e teoria aplicata in quattro lingue... Italiano, Inglese, Spagnolo & Tedesco. Durante tutti questi anni ho suonato con diversi gruppi di diversi stili musicali (Pop, Jazz, Rock, Wienerlied, Metal, Funk, Latin...), e cresciuto come compositore e produttore, sopratutto attraverso il mio <a href="discografia" title="Discografia">Progetto Solista</a> e il mio gruppo di "Rock Progressivo" <a href="http://kolorsofzound.com/" target="_blank" title="Kolors Of Zound">Kolors Of Zound.</a> Alla data ho composto, orchestrato e arrangiato 54 pezzi (di cui 35 sono già pubblicati), e attualmente lavoro nella mia 5a produzione, cui intendo finire il prossimo anno.
