Dal 2011 al 2012 sono stato assunto dal paroliere "Martin Missbichler" per orchestrare, cantare, interpretare e produrre alcune delle sue idee. Durante questo tempo abbiamo raggiunto produrre abbastanza canzoni per un EP chiamato "Rock & Roll - Sing It All".
