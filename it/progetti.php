<hr class="style-one" />
Come solista lavoro veramente da solo, dalla creazione (composizione, orchestrazione e arrangiamenti), fino la produzione (registrazione, edizione, mixing e master).<br />
Come interprete suono la chitarra e il basso, ma gli altri strumenti sono programmati in MIDI.
<hr class="style-one" />
<h5>Produzioni totale fino oggi:</h5>
<a href="discografia">Fragments Of Future Memories (2016)</a><br />
<a href="discografia">MISCHUNG (2009)</a>
</div>

<div class="sub-container">
    <table width="100%">
  <tr>
    <td width="150px">
      <a href="http://kolorsofzound.com" target="_blank"><img class="img" src="../pics/kolors.png" alt="Kolors-Of-Zound" /></a>
    </td>
    <td width="5px">
    </td>
    <td valign="top">
    <h4>KOLORS OF ZOUND <br />(2009 - 2015)</h4>
    <br />
    <a href="http://kolorsofzound.com" target="_blank"><button class="contact-button">Visit Website</button></a>
   </td>
  </tr>
</table>
<hr class="style-one" />
La storia di Kolors Of Zound ha avuto inizio quasi allo stesso tempo che il mio progetto solista. Dopo comporre il suo debut album "Tales From A White Land", ho devuto cercare quattro anni per trovare i musicisti appropriati e così poter registrare e interpretare la sua musica. Dal 2014 al 2015 il gruppo ha suonato attivamente a Vienna, comunque, si è sciolto nel 2015.
<hr class="style-one" />
<h5>Produzioni totale fino oggi:</h5>
<a href="discografia">Tales From A White Land (2014)</a>
<hr class="style-one" />
<h5>Persone che hanno collaborato con Kolors Of Zound:</h5>
<ul>
<li>Hannes Drobetz (Voce)</li>
<li>Christo Popov (Tastiere)</li>
<li>Werner Haider (Basso Live)</li>
<li>Constantin Pammer (Batteria Live)</li>
<li>Roberto Sensi (Basso in studio)</li>
<li>Michal Robert Piatek (Lettere della canzone "Insane")</li>
<li>Dominik Scherr (Batteria in studio della canzone "Orange Hope")</li>
<li>Juan Carlos Andrade (Ingegnere di mixing)</li>
<li>Daniel Celis Arias (Ingegnere di master)</li>
</ul>
</div>

