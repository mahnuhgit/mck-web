Nel 2008 sono stato assunto dal "Grupo Gea - Proyecto K" a Bogotá/Colombia per comporre la musica del musical "Nació Un Campeón". Questo è stato il mio primo lavoro come compositore ed è stato anche molto emozionante lavorare con studenti di recitazione, le cui voci hanno fatto parte della registrazione.
