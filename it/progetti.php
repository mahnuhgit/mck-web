<hr class="style-one" />
Nel 2014 il bassista del mio gruppo "Kolors Of Zound" mi ha invitato a suonare in un altro gruppo dove lui suonaba la tuba. Il "Guglhupf Ensemble" è un grupo di musica viennese composto da due cantanti, un cello, una tuba e una chitarra. All'inizio ero un po' scettico, ma dopo la sua musica ha cominciato a piacermi.
</div>

