Dopo che mi ha aiutato a imparare le mie canzoni preferite, ho capito che la mia carriera professionale dovrebbe essere la musica.<br />
Mi ha anche aiutato con l'esame di ammissione all'università, anche attraverso tutti i miei studi per superare gli ostacoli che mi hanno permesso di realizzare il mio progetto di vita.
 <br />
Le lezioni con Manuel sono divertenti e interessanti, ho sempre trovato risposte concrete e costruttive a tutte le mie domande. Inoltre, vorrei sottolineare che approfondisce tutti i temi senza complicarli.
<br />
Manuel è attualmente una parte essenziale del mio lavoro perché nel corso degli anni sono diventato produttore e Manuel mi aiuta come compositore, arrangiatore e musicista di sessione.
