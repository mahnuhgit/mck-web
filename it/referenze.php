    <br />
Già nella prima lezione mi sentivo molto bene ed ero convinto delle sue conoscenze musicali e delle sue capacità sullo strumento. Grazie a Manuel, sono stato riuscito a ottenere grandi progressi sulla chitarra, ad ampliare la mia conoscenza della teoria musicale e ho scoperto e imparato molti nuovi generi musicali.
 <br />
Grazie alla sua natura paziente e amichevole, le lezioni con lui sono estremamente piacevoli.
 <br />
Nel corso di questi anni sono giunto alla conclusione che Manuel è di gran lunga uno dei migliori insegnanti di chitarra a Vienna e in questo periodo è diventato un buon amico.
