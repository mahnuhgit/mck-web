<hr class="style-one" />
Manuel Calvo Kamper è stato il mio insegnante di chitarra dal 2010 al 2014, uno dei periodi più importanti della mia vita musicale.
A quel tempo, all'età di 16 anni, ho deciso di studiare musica come professione e Manuel mi ha aiutato molto.
<br />
Grazie alle lezioni di Manuel e al suo costante sostegno, ho potuto frequentare l'Università Privata Anton Bruckner a Linz, dove ho conseguito il mio Bachelor of Arts "Instrumental (Singing) Pedagogy - Jazz Guitar" (2017).
<br />
La sua ampia conoscenza teorica mi ha permesso di frequentare l'università con una conoscenza molto avanzata e una formazione auditiva.
Inoltre, i suoi diversi stili musicali (soprattutto progressive rock / metal), il songwriting e la sua conoscenza della chitarra acustica ed elettrica hanno avuto un enorme impatto sulla mia carriera.
<br />
Non solo mi ha aiutato a migliorare come chitarrista, ma anche a diventare un musicista versatile.
<br />
Rimane ancora per me come grande ispirazione, insegnante e amico.

